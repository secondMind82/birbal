import { getDb, serializeWrite } from '../database';
import type { AppNotification } from '../../models/types';

export interface NotificationInput {
  id: string;
  type: AppNotification['type'];
  title: string;
  message?: string | null;
  icon?: string | null;
  read?: boolean;
  entityId?: string | null;
  timelineId?: string | null;
  createdAt?: string | null;
}

interface NotificationRow {
  id: string;
  user_id: string;
  type: string;
  title: string;
  message: string | null;
  icon: string | null;
  read: number;
  entity_id: string | null;
  timeline_id: string | null;
  created_at: string;
}

const NOTIFICATION_COLUMNS =
  'id, user_id, type, title, message, icon, read, entity_id, timeline_id, created_at';

function toNotification(row: NotificationRow): AppNotification {
  return {
    id: row.id,
    userId: row.user_id,
    type: row.type as AppNotification['type'],
    title: row.title,
    message: row.message,
    icon: row.icon,
    read: row.read === 1,
    entityId: row.entity_id,
    timelineId: row.timeline_id,
    createdAt: row.created_at,
  };
}

export async function getAll(userId: string): Promise<AppNotification[]> {
  const db = await getDb();
  const rows = await db.getAllAsync<NotificationRow>(
    `SELECT ${NOTIFICATION_COLUMNS} FROM notifications WHERE user_id = ? ORDER BY read ASC, created_at DESC`,
    userId,
  );
  return rows.map(toNotification);
}

export async function countUnread(userId: string): Promise<number> {
  const db = await getDb();
  const row = await db.getFirstAsync<{ count: number }>(
    'SELECT COUNT(*) AS count FROM notifications WHERE user_id = ? AND read = 0',
    userId,
  );
  return row?.count ?? 0;
}

// INSERT OR IGNORE keeps notification ids idempotent: re-running generation on
// every refresh/app start never duplicates a notification with a stable id.
//
// Returns only the rows that were genuinely written (i.e. did not already
// exist). Callers that surface a notification outside the in-app list (the
// Android system-notification mirror) use this to act exactly once per row, and
// never twice for a row regenerated by every refresh.
export async function insertNew(
  userId: string,
  items: NotificationInput[],
): Promise<NotificationInput[]> {
  if (items.length === 0) return [];
  const inserted: NotificationInput[] = [];
  await serializeWrite(async () => {
    const db = await getDb();
    await db.withExclusiveTransactionAsync(async (txn) => {
      for (const item of items) {
        const result = await txn.runAsync(
          `INSERT OR IGNORE INTO notifications
             (id, user_id, type, title, message, icon, read, entity_id, timeline_id, created_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          item.id,
          userId,
          item.type,
          item.title,
          item.message ?? null,
          item.icon ?? null,
          item.read ? 1 : 0,
          item.entityId ?? null,
          item.timelineId ?? null,
          item.createdAt ?? new Date().toISOString(),
        );
        if (result.changes > 0) inserted.push(item);
      }
    });
  });
  return inserted;
}

export async function upsertAll(userId: string, items: NotificationInput[]): Promise<void> {
  await insertNew(userId, items);
}

/**
 * Inserts the missing rows and refreshes the text of the ones that already exist,
 * keyed by the stable id, returning only the rows that were genuinely inserted.
 *
 * Generated rows (event/reminder countdowns, birthdays, "timeline updated") are
 * derived from live data, so their message can change without their id changing —
 * an edited event time has to refresh its countdown rather than keep the first
 * message it ever produced. Plain INSERT OR IGNORE would freeze that first text
 * forever, which is exactly the stale "Starts in N hours" the Bell kept showing.
 *
 * `read` is preserved so a refresh never re-lights a badge the user already
 * cleared, and only newly-inserted rows are returned so callers that surface a
 * row outside the in-app list (the Android mirror) still act exactly once.
 */
export async function refreshGenerated(
  userId: string,
  items: NotificationInput[],
): Promise<NotificationInput[]> {
  if (items.length === 0) return [];
  const inserted: NotificationInput[] = [];
  await serializeWrite(async () => {
    const db = await getDb();
    await db.withExclusiveTransactionAsync(async (txn) => {
      for (const item of items) {
        const title = item.title;
        const message = item.message ?? null;
        const result = await txn.runAsync(
          `INSERT OR IGNORE INTO notifications
             (id, user_id, type, title, message, icon, read, entity_id, timeline_id, created_at)
           VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
          item.id,
          userId,
          item.type,
          title,
          message,
          item.icon ?? null,
          item.read ? 1 : 0,
          item.entityId ?? null,
          item.timelineId ?? null,
          item.createdAt ?? new Date().toISOString(),
        );
        if (result.changes > 0) {
          inserted.push(item);
          continue;
        }
        // Existing row: update only when the derived text actually changed, so a
        // steady countdown input is not written on every poll.
        await txn.runAsync(
          `UPDATE notifications
             SET title = ?, message = ?
           WHERE id = ? AND user_id = ?
             AND (title IS NOT ? OR message IS NOT ?)`,
          title,
          message,
          item.id,
          userId,
          title,
          message,
        );
      }
    });
  });
  return inserted;
}

export async function markRead(userId: string, id: string): Promise<boolean> {
  return serializeWrite(async () => {
    const db = await getDb();
    const result = await db.runAsync(
      'UPDATE notifications SET read = 1 WHERE id = ? AND user_id = ?',
      id,
      userId,
    );
    return result.changes > 0;
  });
}

/**
 * Removes a notification outright.
 *
 * Used when a notification stops being actionable rather than merely read — an
 * SMS the user ignored or turned into a timeline entry. Leaving it in the list
 * would keep offering Review/Ignore buttons for something already decided, and
 * keep its badge dot lit forever.
 */
export async function remove(userId: string, id: string): Promise<boolean> {
  return serializeWrite(async () => {
    const db = await getDb();
    const result = await db.runAsync(
      'DELETE FROM notifications WHERE id = ? AND user_id = ?',
      id,
      userId,
    );
    return result.changes > 0;
  });
}

export async function markAllRead(userId: string): Promise<void> {
  return serializeWrite(async () => {
    const db = await getDb();
    await db.runAsync(
      'UPDATE notifications SET read = 1 WHERE user_id = ? AND read = 0',
      userId,
    );
  });
}